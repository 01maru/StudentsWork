//-----------------------------------------------------------------------------
// [SECTION] Finalize
//-----------------------------------------------------------------------------

void BaseCollider::Finalize()
{
    deleteFlag_ = TRUE;
}

//-----------------------------------------------------------------------------
// [SECTION] Getter
//-----------------------------------------------------------------------------

MyMath::Matrix BaseCollider::GetWorldMatrix()
{
    if (matWorld_ == nullptr)
    {
        return object_->GetMatWorld();
    }

    return *matWorld_;
}

